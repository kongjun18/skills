#!/usr/bin/env python3
"""Render a curated digest (JSON) into the standard styled HTML page.

This is the *deterministic* half of presentation: the CSS and layout are frozen
here, so every weekly digest looks identical regardless of who generates it. The
*content* -- which papers, cleaned affiliations, the week-in-review prose -- is
the agent's judgment and is passed in as JSON. Change the look here, once, and
every past/future digest re-renders consistently.

Input JSON (stdin or a path):

    {
      "title": "arXiv Systems Digest",
      "subtitle": "Week of Jul 11 - Jul 18, 2026 - ...",
      "window_label": "Jul 11-Jul 18, 2026",
      "window": {"start": "<ISO>", "end": "<ISO>"},  # from fetch output; NOT rendered.
                                          # The next run starts at window.end.
      "stats": [{"n": "75", "label": "fetched"}, ...],
      "review": {                         # week-in-review; HTML inline allowed
        "intro": "<p>...</p>",
        "sections": [{"heading": "Research trends", "items": ["<li-inner>", ...]}]
      },
      "open_threads": [                   # cross-week gap tracking; NOT rendered.
        {"thread": "CXL tiering", "status": "heating|cooling|quiet",
         "note": "..."}                   # next week reads this back; gaps render
      ],                                  # as a normal review section, not from here.
      "highlights": {                     # top picks
        "note": "Top picks - start here.",
        "items": [{"title": "...", "url": "...", "why": "..."}]
      },
      "rings": [                          # Core -> Adjacent
        {"title": "Core: <reader area>", "icon": "...", "blurb": "...",
         "topics": [
           {"title": "ML systems", "icon": "...", "blurb": "...",
            "papers": [
              {"title": "...", "url": "...", "authors": "...",
               "affiliation": "ETH Zurich - NTU Athens",   # cleaned by agent
               "sector": "academia|industry|both|"",       # agent's call
               "date": "2026-07-14", "arxiv_id": "2607.x",
               "primary_category": "cs.AR",                 # badge (top-left of card)
               "cats": "cs.AR, cs.AI",                      # full category list (footer)
               "takeaway": "...", "lead": true,
               "badge": "Your paper"}                        # optional short label
            ]}]}
      ],
      "peripheral": {                     # skim-only tail (the catch-all tier)
        "title": "Peripheral (skim only)",  # optional; catch-all tier title
        "note": "58 in-category papers outside the reader's areas...",
        "items": [{"title": "...", "url": "...", "note": "no link to core"}],
        "tail": "...and ~53 more (...)."
      },
      "footer": "Generated by the pull-recent-papers pipeline. ..."
    }

Usage:
    python3 render_html.py DIR/digest-YYYY-Www.json --out-dir DIR   # -> DIR/digest-YYYY-Www.html
    python3 render_html.py digest.json -o out.html
    cat digest.json | python3 render_html.py                      # -> stdout

Outputs belong in the user's digest directory, never inside the skills
repository; the script refuses such an output path.
"""
