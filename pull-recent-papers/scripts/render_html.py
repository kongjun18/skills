# sector value -> (css class, label). Empty/unknown -> no pill.
SECTOR = {
    "academia": ("aca", "academia"),
    "industry": ("ind", "industry"),
    "both": ("mix", "academia + industry"),
}


def esc(s: str) -> str:
    return html.escape(s or "", quote=True)


def link(url: str, text: str, cls: str = "") -> str:
    c = f' class="{cls}"' if cls else ""
    return (f'<a href="{esc(url)}" target="_blank" rel="noopener"{c}>'
            f'{esc(text)}</a>')


def render_affil(paper: dict) -> str:
    aff = paper.get("affiliation", "").strip()
    if not aff:
        return ""
    sect = paper.get("sector", "").strip().lower()
    pill = ""
    if sect in SECTOR:
        cls, label = SECTOR[sect]
        pill = f'<span class="sect {cls}">{label}</span>'
    return (f'        <p class="affil">\U0001f3db️ '
            f'<span class="org">{esc(aff)}</span>{pill}</p>\n')


def render_card(paper: dict) -> str:
    lead = " lead" if paper.get("lead") else ""
    lead_tag = '<span class="lead-tag">★ highlight</span>' if paper.get("lead") else ""
    badge = f'<span class="tag">{esc(paper["badge"])}</span>' if paper.get("badge") else ""
    return f"""      <article class="card{lead}">
        <div class="card-head">
          <span class="badge">{esc(paper.get('primary_category', ''))}</span>
          <span class="date">{esc(paper.get('date', ''))}</span>
          {badge}{lead_tag}
        </div>
        <h3>{link(paper.get('url', ''), paper.get('title', ''))}</h3>
        <p class="authors">{esc(paper.get('authors', ''))}</p>
{render_affil(paper)}        <p class="abstract">{esc(paper.get('takeaway', ''))}</p>
        <p class="meta">{link(paper.get('url', ''), 'arXiv:' + paper.get('arxiv_id', ''))}
           · <span class="cats">{esc(paper.get('cats', ''))}</span></p>
      </article>"""


def render(d: dict) -> str:
    p: list[str] = []
    p.append(f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{esc(d.get('title', 'arXiv Digest'))} · {esc(d.get('window_label', ''))}</title>
<style>{CSS}</style>
</head>
<body>
<div class="wrap">
  <header class="top">
    <h1>{esc(d.get('title', 'arXiv Digest'))}</h1>
    <div class="sub">{esc(d.get('subtitle', ''))}</div>
    <div class="stats">""")
    for s in d.get("stats", []):
        p.append(f'      <div class="stat"><b>{esc(str(s.get("n", "")))}</b>'
                 f'<span>{esc(s.get("label", ""))}</span></div>')
    p.append("""    </div>
  </header>""")

    # Week in review -- prose is agent-authored; inline HTML in items is kept.
    rev = d.get("review")
    if rev:
        p.append('\n  <div class="review">')
        p.append('    <h2>\U0001f4ca Week in review</h2>')
        if rev.get("intro"):
            p.append(f'    {rev["intro"]}')
        for sec in rev.get("sections", []):
            p.append(f'    <h3>{esc(sec.get("heading", ""))}</h3>')
            p.append('    <ul>')
            for it in sec.get("items", []):
                p.append(f'      <li>{it}</li>')
            p.append('    </ul>')
        p.append('  </div>')

    # Highlights
    hi = d.get("highlights")
    if hi:
        p.append('\n  <div class="leads">')
        p.append('    <h2>⭐ Highlights</h2>')
        if hi.get("note"):
            p.append(f'    <p>{esc(hi["note"])}</p>')
        p.append('    <ol>')
        for it in hi.get("items", []):
            why = f' <span class="why">— {it["why"]}</span>' if it.get("why") else ""
            p.append(f'      <li>{link(it.get("url", ""), it.get("title", ""))}{why}</li>')
        p.append('    </ol>')
        p.append('  </div>')

    # Rings -> topics -> cards
    for ring in d.get("rings", []):
        head = f'{ring.get("icon", "")} {esc(ring.get("title", ""))}'
        if ring.get("blurb"):
            head += f' — {esc(ring["blurb"])}'
        p.append(f'\n  <div class="ring-head">{head}</div>')
        for topic in ring.get("topics", []):
            papers = topic.get("papers", [])
            p.append(f"""    <section class="topic">
      <div class="topic-head">
        <h2><span class="icon">{esc(topic.get('icon', ''))}</span>{esc(topic.get('title', ''))}
          <span class="count">{len(papers)}</span></h2>
        <p class="blurb">{esc(topic.get('blurb', ''))}</p>
      </div>
      <div class="cards">
""")
            for paper in papers:
                p.append(render_card(paper))
            p.append("""      </div>
    </section>""")

    # Peripheral
    per = d.get("peripheral")
    if per:
        p.append('\n  <div class="peripheral">')
        p.append(f'    <h2>{esc(per.get("title", "Peripheral (skim only)"))}</h2>')
        if per.get("note"):
            p.append(f'    <p>{esc(per["note"])}</p>')
        p.append('    <ul>')
        for it in per.get("items", []):
            note = f' <span class="note">· {esc(it["note"])}</span>' if it.get("note") else ""
            p.append(f'      <li>{link(it.get("url", ""), it.get("title", ""))}{note}</li>')
        if per.get("tail"):
            p.append(f'      <li class="note">{esc(per["tail"])}</li>')
        p.append('    </ul>')
        p.append('  </div>')

    p.append(f"""
  <footer>
    {esc(d.get('footer', ''))}
  </footer>
</div>
</body>
</html>""")
    return "\n".join(p)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("input", nargs="?", help="digest JSON path (default: stdin)")
    ap.add_argument("-o", "--output", help="write HTML here (default: stdout)")
    ap.add_argument("--out-dir", help="write <input-stem>.html into this directory")
    args = ap.parse_args()
    if args.out_dir:
        if not args.input:
            ap.error("--out-dir needs an input path to name the output")
        args.output = str(Path(args.out_dir).expanduser() / (Path(args.input).stem + ".html"))
    if args.output:
        repo = Path(__file__).resolve().parents[2]
        target = Path(args.output).expanduser().resolve()
        if repo in target.parents:
            ap.error(f"refusing to write inside the skills repository ({repo}); "
                     "write to the digest directory instead")

    raw = open(args.input) if args.input else sys.stdin
    data = json.load(raw)
    out = render(data)

    if args.output:
        with open(args.output, "w") as f:
            f.write(out)
        print(f"wrote {args.output}: {len(out)} bytes", file=sys.stderr)
    else:
        sys.stdout.write(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
